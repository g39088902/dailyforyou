export interface SourceSeed {
  key: string; // 稳定标识：reuters-world
  name: string; // 请求路径 / DB 的 source_name：reuters
  subType?: string; // DB 的 sub_type：world，无则为空串
  params?: Record<string, string>; // 请求 query：{"type":"world"}
  adapter: string; // 对应 routes/{adapter}.ts
  label: string; // 中文名称：路透社·国际
  category?: string; // 分类：财经、科技、热点、社区、开发等
  type?: string; // 副标题：国际、电报、人气榜
  link?: string; // 源站主页或频道链接
  logoText?: string; // 文字徽标文案（默认取 label 首字）
  logoColor?: string; // 文字徽标底色（默认按 key 稳定哈希取色）
  logoUrl?: string; // 外链 logo，优先级最高
  order: number; // 默认排序序号
  defaultOn?: boolean; // 默认开启（默认 true）
  enabled?: number; // 人工开关 / 可用状态（1=可用, 0=禁用/缺少适配器）
  retired?: number; // 0=正常, 1=已退役保留历史
}

