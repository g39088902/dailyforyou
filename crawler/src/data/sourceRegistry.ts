/**
 * 稳定 32 位整型哈希，保证同一 key 在任何环境取色绝对一致
 */
export const hash32 = (str: string): number => {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
};

/**
 * 推导徽标首字与底色
 */
export const resolveLogoDefaults = (seed: SourceSeed): { logoText: string; logoColor: string } => {
  const logoText = seed.logoText || (seed.label ? seed.label.trim().charAt(0) : "新");
  const logoColor = seed.logoColor || PALETTE[hash32(seed.key) % PALETTE.length];
  return { logoText, logoColor };
};

